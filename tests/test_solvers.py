from src.sudoku import Sudoku
from src.constraint_propagation import propagate


def test_constraint_propagation():
    puzzle = [
        [5, 3, 0, 0, 7, 0, 0, 0, 0],
        [6, 0, 0, 1, 9, 5, 0, 0, 0],
        [0, 9, 8, 0, 0, 0, 0, 6, 0],

        [8, 0, 0, 0, 6, 0, 0, 0, 3],
        [4, 0, 0, 8, 0, 3, 0, 0, 1],
        [7, 0, 0, 0, 2, 0, 0, 0, 6],

        [0, 6, 0, 0, 0, 0, 2, 8, 0],
        [0, 0, 0, 4, 1, 9, 0, 0, 5],
        [0, 0, 0, 0, 8, 0, 0, 7, 9],
    ]

    sudoku = Sudoku(puzzle)

    result = propagate(sudoku)

    assert result is True
    assert sudoku.empty_count() < 51

    # Cell (0, 2) has only one possible value: 4.
    assert sudoku.get(0, 2) == 4